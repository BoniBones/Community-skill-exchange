export const dictionaries: Record<SupportedLocale, Record<TranslationKey, string>> = {
  'es-AR': esAr,
  en,
};

export function getDeviceLocaleCode(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale || 'es-AR';
  } catch {
    return 'es-AR';
  }
}

let activeLocale: SupportedLocale = 'es-AR';
const listeners = new Set<(locale: SupportedLocale) => void>();

export function isSupportedLocale(value: string | null | undefined): value is SupportedLocale {
  return value === 'es-AR' || value === 'en';
}

export function getActiveLocale(): SupportedLocale {
  return activeLocale;
}

export function setActiveLocale(next: SupportedLocale): void {
  activeLocale = next;
  listeners.forEach((listener) => listener(next));
  void setStoredItem(LOCALE_STORAGE_KEY, next);
}

export async function hydrateLocale(): Promise<SupportedLocale> {
  const stored = await getStoredItem(LOCALE_STORAGE_KEY);
  if (isSupportedLocale(stored) && stored !== activeLocale) {
    activeLocale = stored;
    listeners.forEach((listener) => listener(stored));
  }
  return activeLocale;
}

export function t(
  key: TranslationKey,
  paramsOrLocale?: TranslationParams | SupportedLocale,
  maybeLocale?: SupportedLocale,
): string {
  let params: TranslationParams | undefined;
  let locale: SupportedLocale = activeLocale;
  if (typeof paramsOrLocale === 'string') {
    locale = paramsOrLocale;
  } else if (paramsOrLocale) {
    params = paramsOrLocale;
    if (maybeLocale) locale = maybeLocale;
  }

  const resolvedLocale: SupportedLocale = isSupportedLocale(locale) ? locale : 'es-AR';
  let template: string = (dictionaries[resolvedLocale] ?? dictionaries['es-AR'])[key] ?? dictionaries['es-AR'][key];
  if (params) {
    for (const [paramKey, paramValue] of Object.entries(params)) {
      template = template.split(`{${paramKey}}`).join(String(paramValue));
    }
  }
  return template;
}

export type TranslateFn = (key: TranslationKey, params?: TranslationParams) => string;

interface I18nContextValue {
  locale: SupportedLocale;
  setLocale: (next: SupportedLocale) => void;
  t: TranslateFn;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<SupportedLocale>(activeLocale);

  useEffect(() => {
    const listener = (next: SupportedLocale) => setLocaleState(next);
    listeners.add(listener);
    void hydrateLocale();
    return () => {
      listeners.delete(listener);
    };
  }, []);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale: setActiveLocale,
      t: (key, params) => t(key, params, locale),
    }),
    [locale],
  );

  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  const [fallbackLocale, setFallbackLocale] = useState<SupportedLocale>(activeLocale);

  useEffect(() => {
    if (ctx) return;
    const listener = (next: SupportedLocale) => setFallbackLocale(next);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, [ctx]);

  if (ctx) return ctx;

  return {
    locale: fallbackLocale,
    setLocale: setActiveLocale,
    t: (key, params) => t(key, params, fallbackLocale),
  };
}

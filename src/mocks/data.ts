function session(
  id: string,
  activityId: string,
  learnerId: string,
  startsAt: string,
  state: Session['state'],
): Session {
  const a = activities.find((x) => x.id === activityId)!;
  return {
    id,
    activityId,
    learnerId,
    instructorId: a.instructorId,
    startsAt,
    endsAt: plusMinutes(startsAt, a.durationMin),
    state,
    price: { ...a.payment },
  };
}


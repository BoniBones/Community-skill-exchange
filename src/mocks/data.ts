/** UTC ISO string for `days` from today at `hourBA`:`minute` Buenos Aires time. */
function at(days: number, hourBA: number, minute = 0): string {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() + days);
  d.setUTCHours(hourBA + 3, minute, 0, 0);
  return d.toISOString();
}
function plusMinutes(iso: string, min: number): string {
  return new Date(new Date(iso).getTime() + min * 60_000).toISOString();
}

